local out = {}
for pi, p in ipairs(patterns) do
  local ok, re = pcall(vim.regex, p)
  local row = {}
  for si, s in ipairs(strings) do
    if ok then
      local a, b = re:match_str(s)
      row[si] = a and (a .. ':' .. b) or '-'
    else
      row[si] = 'ERR'
    end
  end
  out[pi] = table.concat(row, ' ')
end

vim.api.nvim_buf_set_lines(0, 0, -1, false, { 'say foo bar', 'nothing' })
local re = vim.regex([[\<bar]])
local l0 = { re:match_line(0, 0) }
local l1 = { re:match_line(0, 1) }
local l2 = { re:match_line(0, 0, 4) }

io.stdout:write(vim.json.encode({ matches = out, line = { l0, l1, l2 } }) .. "\n")
