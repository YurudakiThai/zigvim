local strings = {
  'zsh', 'zsh -f', 'zshrc', 'tclsh', 'wish8', 'expect', 'gnuplot', 'make', 'gmake -f', 'perl', 'python3',
  'node', 'ruby', 'bash', '#!/bin/bash', '#!/usr/bin/env zsh', 'foo bar', 'foobar', 'xfoobarbaz', 'xxx',
