-- TASK-111: vim.fn editing helpers
local out = {}
vim.api.nvim_buf_set_lines(0, 0, -1, false, {'alpha', 'beta', 'gamma'})
local b = vim.api.nvim_get_current_buf()
local function cap(f, ...)
  local ok, res = pcall(f, ...)
  return ok and res or 'ERR: '..tostring(res)
end
out.getline1 = cap(vim.fn.getline, 1)
out.getline_dot = (function() vim.fn.cursor(2,1) return cap(vim.fn.getline, '.') end)()
out.getline_dollar = cap(vim.fn.getline, '$')
out.getline_range = cap(vim.fn.getline, 1, 2)
out.getline_line2 = cap(vim.fn.getline, 2)
out.setline = (function() vim.fn.setline(2, 'BETA') return vim.api.nvim_buf_get_lines(0,1,2,false)[1] end)()
out.setline_list = (function() vim.fn.setline(1, {'one','two'}) return table.concat(vim.api.nvim_buf_get_lines(0,0,3,false), '|') end)()
vim.api.nvim_buf_set_lines(0, 0, -1, false, {'a','b','c'})
out.append = (function() vim.fn.append(1, 'inserted') return table.concat(vim.api.nvim_buf_get_lines(0,0,-1,false),'|') end)()
out.line_dot = (function() vim.fn.cursor(3,1) return cap(vim.fn.line, '.') end)()
out.line_dollar = cap(vim.fn.line, '$')
out.col_dot = (function() vim.fn.cursor(1,2) return cap(vim.fn.col, '.') end)()
out.col_dollar = (function() vim.fn.cursor(1,1) return cap(vim.fn.col, '$') end)()
out.bufnr_pct = cap(vim.fn.bufnr, '%')
out.bufnr_cur = cap(vim.fn.bufnr, b)
out.bufnr_missing = cap(vim.fn.bufnr, 999)
out.bufname_cur = cap(vim.fn.bufname, '%')
out.bufexists = {cap(vim.fn.bufexists, b), cap(vim.fn.bufexists, 999)}
out.getbufline = cap(vim.fn.getbufline, b, 1, 2)
out.getbufvar_missing = cap(vim.fn.getbufvar, b, 'nope')
out.getbufvar_default = cap(vim.fn.getbufvar, b, 'nope', 'fallback')
vim.api.nvim_buf_set_var(b, 'tv', 42)
out.getbufvar = cap(vim.fn.getbufvar, b, 'tv')
out.setbufvar = (function() vim.fn.setbufvar(b, 'sv', 7) return vim.api.nvim_buf_get_var(b, 'sv') end)()
out.getwinvar = (function() vim.api.nvim_win_set_var(0, 'wv', 9) return cap(vim.fn.getwinvar, 0, 'wv') end)()
vim.fn.setreg('z', 'hello')
out.getreg = cap(vim.fn.getreg, 'z')
out.getreg_type = cap(vim.fn.getregtype, 'z')
out.strwidth = cap(vim.fn.strwidth, 'hello')
out.strchars = cap(vim.fn.strchars, '日本語')
out.strlen = cap(vim.fn.strlen, 'hello')
out.toupper = cap(vim.fn.toupper, 'abc')
out.tolower = cap(vim.fn.tolower, 'ABC')
out.split = cap(vim.fn.split, 'a,b,c', ',')
out.join = cap(vim.fn.join, {'a','b'}, '+')
out.stridx = cap(vim.fn.stridx, 'hello', 'll')
out.strpart = cap(vim.fn.strpart, 'hello', 1, 3)
out.repeat_str = cap(vim.fn['repeat'], 'ab', 3)
out.escape = cap(vim.fn.escape, 'a.b', '.')
out.fnameescape = cap(vim.fn.fnameescape, 'a b')
out.shellescape = cap(vim.fn.shellescape, 'a b')
out.exists_func = cap(vim.fn.exists, '*getline')
out.exists_var = (function() vim.g.exv = 1 return cap(vim.fn.exists, 'g:exv') end)()
out.exists_var_missing = cap(vim.fn.exists, 'g:nope')
out.exists_opt = cap(vim.fn.exists, '&tabstop')
out.exists_cmd = cap(vim.fn.exists, ':edit')
