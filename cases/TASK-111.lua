out.has_unix = cap(vim.fn.has, 'unix')
out.mode = cap(vim.fn.mode)
out.winheight = cap(vim.fn.winheight, 0)
out.winwidth = cap(vim.fn.winwidth, 0)
out.winnr = cap(vim.fn.winnr)
