-- Regenerate src/lua/vim/_default_hl.lua from the oracle's built-in highlight groups:
--   nvim --headless --clean -l scripts/gen_default_hl.lua > src/lua/vim/_default_hl.lua
local function ser(v)
  if type(v) == 'table' then
    local keys = vim.tbl_keys(v)
    table.sort(keys, function(a, b) return tostring(a) < tostring(b) end)
    local parts = {}
    for _, k in ipairs(keys) do
      local key = type(k) == 'string' and k:match('^[%a_][%w_]*$') and k or ('[' .. string.format('%q', k) .. ']')
      parts[#parts + 1] = key .. '=' .. ser(v[k])
    end
    return '{' .. table.concat(parts, ',') .. '}'
  elseif type(v) == 'string' then
    return string.format('%q', v)
  end
  return tostring(v)
end

local out = {}
for _, bg in ipairs({ 'dark', 'light' }) do
  vim.o.background = bg
  local groups = vim.api.nvim_get_hl(0, {})
  local lines = {}
  local names = vim.tbl_keys(groups)
  table.sort(names)
  for _, name in ipairs(names) do
    lines[#lines + 1] = '    [' .. string.format('%q', name) .. '] = ' .. ser(groups[name]) .. ','
  end
  out[#out + 1] = '  ' .. bg .. ' = {\n' .. table.concat(lines, '\n') .. '\n  },'
end
io.stdout:write('-- Generated by scripts/gen_default_hl.lua from Neovim ' .. tostring(vim.version())
  .. ' (nvim --clean). Do not edit.\nreturn {\n' .. table.concat(out, '\n') .. '\n}\n')
