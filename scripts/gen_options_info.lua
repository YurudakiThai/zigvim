-- Regenerate src/lua/vim/_options_info.lua from the oracle's option metadata:
--   nvim --headless --clean -l scripts/gen_options_info.lua > src/lua/vim/_options_info.lua
-- Defaults that depend on the machine (paths, shell, terminal size) are dropped;
-- zigvim's own option defaults supply those.
local env_dependent = {
  runtimepath = true, packpath = true, shell = true, shellcmdflag = true, shellpipe = true,
  shellredir = true, shellxquote = true, shellxescape = true, shellquote = true, helpfile = true,
  directory = true, backupdir = true, undodir = true, viewdir = true, columns = true, lines = true,
  term = true, ttytype = true, path = true, cdpath = true, makeprg = true, grepprg = true,
  shada = true, shadafile = true, spellfile = true, titleold = true, keywordprg = true,
}
local function ser(v)
  if type(v) == 'string' then
    return string.format('%q', v)
  end
  return tostring(v)
end
local all = vim.api.nvim_get_all_options_info()
local names = vim.tbl_keys(all)
table.sort(names)
local out = { '-- Generated by scripts/gen_options_info.lua from Neovim ' .. tostring(vim.version()) .. ' (nvim --clean). Do not edit.', 'return {' }
for _, name in ipairs(names) do
  local i = all[name]
  local fields = {
    'shortname=' .. ser(i.shortname), 'type=' .. ser(i.type), 'scope=' .. ser(i.scope),
    'global_local=' .. ser(i.global_local), 'commalist=' .. ser(i.commalist), 'flaglist=' .. ser(i.flaglist),
    'allows_duplicates=' .. ser(i.allows_duplicates),
  }
  if not env_dependent[name] then
    fields[#fields + 1] = 'default=' .. ser(i.default)
  end
  out[#out + 1] = '  [' .. ser(name) .. '] = {' .. table.concat(fields, ',') .. '},'
end
out[#out + 1] = '}'
io.stdout:write(table.concat(out, '\n'), '\n')
