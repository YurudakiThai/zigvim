-- Lua implementation of Neovim's runtime/plugin/rplugin.vim.
--
-- Neovim loads a generated manifest from stdpath('data')/rplugin.vim and
-- provides :UpdateRemotePlugins to regenerate it by asking each remote plugin
-- host for its specs. zigvim has no remote plugin hosts yet, so the manifest
-- is generated with the same header and host sections but without
-- remote#host#RegisterPlugin() lines; the limitation is noted in
-- docs/DISTRO-LOOP.md section 6.

local api = vim.api

local M = {}

local function manifest_path()
  local override = os.getenv('NVIM_RPLUGIN_MANIFEST')
  if override and override ~= '' then
    return vim.fn.fnamemodify(override, ':p')
  end
  return vim.fn.stdpath('data') .. '/rplugin.vim'
end

local function readable(path)
  local f = io.open(path, 'r')
  if f then
    f:close()
    return true
  end
  return false
end

local function load_manifest()
  local path = manifest_path()
  vim.g.loaded_remote_plugins = path
  if readable(path) then
    pcall(vim.cmd.source, path)
  end
end

local function write_manifest()
  local path = manifest_path()
  local hosts = { 'perl', 'node', 'python3', 'ruby' }
  local lines = { '" rplugin.vim -- generated by :UpdateRemotePlugins', '' }
  for _, host in ipairs(hosts) do
    lines[#lines + 1] = '" ' .. host .. ' plugins'
    lines[#lines + 1] = ''
  end
  local dir = path:match('^(.*)/[^/]*$')
  if dir and dir ~= '' then
    vim.fn.mkdir(dir, 'p')
  end
  local f = assert(io.open(path, 'w'))
  f:write(table.concat(lines, '\n') .. '\n')
  f:close()
  vim.g.loaded_remote_plugins = path
  vim.api.nvim_echo({ { ('remote/host: generated rplugin manifest: %s'):format(path) } }, true, {})
end

function M.update_remote_plugins()
  write_manifest()
end

function M.setup()
  if vim.g.loaded_remote_plugins then
    return
  end
  load_manifest()
  api.nvim_create_user_command('UpdateRemotePlugins', function()
    M.update_remote_plugins()
  end, { desc = 'Update the remote plugin manifest' })
end

return M
